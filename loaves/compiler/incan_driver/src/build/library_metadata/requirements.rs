//! Portable checked planning inputs for ordinary metadata replay (#1337/#1698).
//!
//! Physical path bindings are reconstructed from current declarations and admitted providers. Persisted native
//! execution plans, generated output roots and their leases never enter this contract.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use incan_frontend::ast::Span;
use incan_frontend::library_exports::CheckedNamedExport;
use incan_frontend::library_manifest::CheckedExportReplay;
use incan_frontend::library_manifest_index::LibraryManifestIndex;
use incan_provider::dependency_resolver::{InlineRustImport, ResolvedDependencies, resolve_reachable_dependencies};
use incan_provider::requirements::{
    ProjectRequirements, declared_stdlib_dependency, merge_project_requirement_dependencies,
};
use oven_model::lock::CargoFeatureSelection;
use oven_model::manifest::{DependencySource, DependencySpec, GitReference, ProjectManifest};
use serde::{Deserialize, Serialize};

use crate::backend::selection::BackendExecutionReceipt;
use crate::error::{CliError, CliResult};

/// Current preparation requirements captured by the same successful checked library compilation.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckedLibraryRequirements {
    /// Independent planning contract version; old or incomplete knowledge is a miss, never an empty requirement set.
    pub schema_version: u32,
    /// Exact modules used by checked source, projected through this command's admitted provider catalog on replay.
    pub used_module_paths: BTreeSet<Vec<String>>,
    /// Source-derived linking facets before current provider requirements are applied.
    pub stdlib_facets: Vec<String>,
    /// Source-derived dependency requirements with portable current-binding selectors.
    dependencies: Vec<CheckedRustRequirement>,
    /// Source-derived toolchain path requirements, retaining the same binding selectors.
    sdk_path_dependencies: Vec<CheckedRustRequirement>,
    /// Actual authored Rust use sites needed by current manifest dependency resolution.
    imports: Vec<CheckedRustUse>,
    /// Caller-authored Rust crates, excluding compiler-owned standard facets and sysroot.
    pub source_inline_crates: BTreeSet<String>,
    /// Explicit checked export identity-to-shape records used by existing caller-facet consumers.
    pub checked_exports: Vec<CheckedExportReplay>,
    /// Entrypoint module prefix removed only from the caller-selection projection.
    pub entry_module: Vec<String>,
    /// Source provenance relative to this package, retained without parsing source again.
    pub source_modules: BTreeMap<String, Vec<String>>,
    /// Exact checked Rust extern labels retained in the ordinary build report.
    pub rust_extern_paths: Vec<String>,
    /// Complete Rust ABI queries promised by this preparation.
    pub rust_abi_queries: BTreeSet<String>,
    /// Existing generated-backend receipt; it describes immutable generated bytes, not a native execution plan.
    pub backend: Option<BackendExecutionReceipt>,
}

/// Portable use site; byte spans are provenance, never name-resolution authority on replay.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct CheckedRustUse {
    crate_name: String,
    import_path: String,
    version: Option<String>,
    features: Vec<String>,
    source_relative_path: String,
    start: usize,
    end: usize,
    is_test_context: bool,
}

/// Exact non-path dependency fields plus a current declaration selector for physical sources.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct CheckedRustRequirement {
    crate_name: String,
    version: Option<String>,
    features: Vec<String>,
    default_features: bool,
    optional: bool,
    package: Option<String>,
    source: CheckedRustSource,
}

/// Logical source authority; no persisted generated or Store path can become a current dependency coordinate.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", deny_unknown_fields)]
enum CheckedRustSource {
    Registry,
    Git {
        url: String,
        reference: CheckedGitReference,
    },
    Provider {
        alias: String,
    },
    DeclaredRust {
        alias: String,
    },
    StandardLibrary {
        crate_name: String,
    },
}

/// Preserve the exact Git selection class as well as its spelling.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", content = "value")]
enum CheckedGitReference {
    Branch(String),
    Tag(String),
    Rev(String),
}

/// Inputs from one successful checked preparation, captured before current provider coordinates are projected.
pub(crate) struct CheckedLibraryCapture<'a> {
    pub project: &'a ProjectManifest,
    pub index: &'a LibraryManifestIndex,
    pub requirements: &'a ProjectRequirements,
    pub imports: &'a [InlineRustImport],
    pub exports: &'a [CheckedNamedExport],
    pub version: &'a str,
    pub used_module_paths: BTreeSet<Vec<String>>,
    pub source_modules: BTreeMap<String, Vec<String>>,
    pub entry_module: Vec<String>,
    pub rust_abi_queries: BTreeSet<String>,
    pub rust_extern_paths: Vec<String>,
    pub backend: Option<BackendExecutionReceipt>,
}

impl CheckedLibraryRequirements {
    /// Capture fully checked source requirements before current provider coordinates are added.
    pub(crate) fn capture(inputs: CheckedLibraryCapture<'_>) -> CliResult<Self> {
        let CheckedLibraryCapture {
            project,
            index,
            requirements,
            imports,
            exports,
            version,
            used_module_paths,
            source_modules,
            entry_module,
            rust_abi_queries,
            rust_extern_paths,
            backend,
        } = inputs;
        let name = project
            .project
            .as_ref()
            .and_then(|project| project.name.as_deref())
            .ok_or_else(|| invalid("checked library planning contract requires a declared package name"))?;
        let imports = imports
            .iter()
            .map(|value| {
                Ok(CheckedRustUse {
                    crate_name: value.crate_name.clone(),
                    import_path: value.import_path.clone(),
                    version: value.version.clone(),
                    features: value.features.clone(),
                    source_relative_path: source_relative(project.project_root(), &value.file_path)?,
                    start: value.span.start,
                    end: value.span.end,
                    is_test_context: value.is_test_context,
                })
            })
            .collect::<CliResult<Vec<_>>>()?;
        let result = Self {
            schema_version: 1,
            used_module_paths,
            stdlib_facets: requirements.stdlib_facets.clone(),
            dependencies: requirements
                .dependencies
                .iter()
                .map(|value| CheckedRustRequirement::capture(value, project, index))
                .collect::<CliResult<_>>()?,
            sdk_path_dependencies: requirements
                .sdk_path_dependencies
                .iter()
                .map(|value| CheckedRustRequirement::capture(value, project, index))
                .collect::<CliResult<_>>()?,
            source_inline_crates: imports
                .iter()
                .filter(|value| {
                    !incan_lang::lang::stdlib::facets::is_facet(&value.crate_name) && value.crate_name != "std"
                })
                .map(|value| value.crate_name.clone())
                .collect(),
            imports,
            checked_exports: exports
                .iter()
                .map(|value| {
                    CheckedExportReplay::from_checked(name, version, value).map_err(|error| invalid(error.to_string()))
                })
                .collect::<CliResult<_>>()?,
            source_modules,
            entry_module,
            rust_abi_queries,
            rust_extern_paths,
            backend,
        };
        result.validate()?;
        Ok(result)
    }

    /// Validate the complete contract before using any requirement or checked export.
    pub fn validate(&self) -> CliResult<()> {
        if self.schema_version != 1 || self.entry_module.is_empty() || self.source_modules.is_empty() {
            return Err(invalid("missing or unsupported checked library planning authority"));
        }
        for path in self
            .source_modules
            .keys()
            .chain(self.imports.iter().map(|value| &value.source_relative_path))
        {
            safe_relative(path)?;
        }
        for import in &self.imports {
            if import.start > import.end || !self.source_modules.contains_key(&import.source_relative_path) {
                return Err(invalid("checked Rust use has invalid source provenance"));
            }
        }
        if !self.source_modules.values().any(|module| module == &self.entry_module)
            || self
                .source_modules
                .values()
                .chain(self.used_module_paths.iter())
                .any(|path| path.is_empty() || path.iter().any(|part| part.trim().is_empty()))
        {
            return Err(invalid("checked requirement module provenance is incomplete"));
        }
        for export in &self.checked_exports {
            export.to_checked().map_err(|error| invalid(error.to_string()))?;
        }
        if let Some(backend) = &self.backend {
            backend.verify_identity().map_err(|error| invalid(error.to_string()))?;
        }
        Ok(())
    }

    /// Restore current source-derived requirements, then let the existing provider planner add current coordinates.
    pub fn current_requirements(
        &self,
        project: &ProjectManifest,
        index: &LibraryManifestIndex,
    ) -> CliResult<ProjectRequirements> {
        self.validate()?;
        Ok(ProjectRequirements {
            stdlib_facets: self.stdlib_facets.clone(),
            dependencies: self
                .dependencies
                .iter()
                .map(|value| value.current(project, index))
                .collect::<CliResult<_>>()?,
            sdk_path_dependencies: self
                .sdk_path_dependencies
                .iter()
                .map(|value| value.current(project, index))
                .collect::<CliResult<_>>()?,
            sdk_dependency_rebindings: Vec::new(),
            sdk_artifact_projections: Vec::new(),
        })
    }

    /// Resolve authored Rust uses through the current project manifest without reparsing Incan source.
    pub fn current_dependencies(
        &self,
        project: &ProjectManifest,
        requirements: &ProjectRequirements,
    ) -> CliResult<(ResolvedDependencies, Vec<InlineRustImport>)> {
        self.validate()?;
        let imports = self
            .imports
            .iter()
            .map(|value| InlineRustImport {
                crate_name: value.crate_name.clone(),
                import_path: value.import_path.clone(),
                version: value.version.clone(),
                features: value.features.clone(),
                span: Span::new(value.start, value.end),
                file_path: project.project_root().join(&value.source_relative_path),
                is_test_context: value.is_test_context,
            })
            .collect::<Vec<_>>();
        let mut resolved =
            resolve_reachable_dependencies(Some(project), &imports, true, &CargoFeatureSelection::default()).map_err(
                |errors| {
                    invalid(format!(
                        "current checked Rust requirement resolution failed: {errors:?}"
                    ))
                },
            )?;
        merge_project_requirement_dependencies(&mut resolved, requirements)?;
        Ok((resolved, imports))
    }

    /// Rehydrate the caller-selection view while keeping declaration canonical identities intact.
    pub fn caller_exports(&self) -> CliResult<Vec<CheckedNamedExport>> {
        self.validate()?;
        self.checked_exports
            .iter()
            .map(|record| {
                let mut export = record.to_checked().map_err(|error| invalid(error.to_string()))?;
                if export.identity.source_path.starts_with(&self.entry_module) {
                    export.identity.source_path.drain(..self.entry_module.len());
                }
                Ok(export)
            })
            .collect()
    }
}

impl CheckedRustRequirement {
    /// Capture exact selected fields, replacing only a physical path by its current declaration authority.
    fn capture(value: &DependencySpec, project: &ProjectManifest, index: &LibraryManifestIndex) -> CliResult<Self> {
        let source = match &value.source {
            DependencySource::Registry => CheckedRustSource::Registry,
            DependencySource::Git { url, reference } => CheckedRustSource::Git {
                url: url.clone(),
                reference: match reference {
                    GitReference::Branch(value) => CheckedGitReference::Branch(value.clone()),
                    GitReference::Tag(value) => CheckedGitReference::Tag(value.clone()),
                    GitReference::Rev(value) => CheckedGitReference::Rev(value.clone()),
                },
            },
            DependencySource::Path { path } => {
                if let Some(metadata) = index.loaded_artifact(&value.crate_name)
                    && same_path(path, &metadata.crate_root)?
                {
                    CheckedRustSource::Provider {
                        alias: value.crate_name.clone(),
                    }
                } else if let Some(declared) = project.rust_dependencies().get(&value.crate_name)
                    && let DependencySource::Path { path: selected } = &declared.source
                    && same_path(path, selected)?
                {
                    CheckedRustSource::DeclaredRust {
                        alias: value.crate_name.clone(),
                    }
                } else if let Some(declared) = declared_stdlib_dependency(&value.crate_name)?
                    && let DependencySource::Path { path: selected } = &declared.source
                    && same_path(path, selected)?
                {
                    CheckedRustSource::StandardLibrary {
                        crate_name: value.crate_name.clone(),
                    }
                } else {
                    return Err(invalid(format!(
                        "checked dependency `{}` has no portable current source binding",
                        value.crate_name
                    )));
                }
            }
        };
        Ok(Self {
            crate_name: value.crate_name.clone(),
            version: value.version.clone(),
            features: value.features.clone(),
            default_features: value.default_features,
            optional: value.optional,
            package: value.package.clone(),
            source,
        })
    }

    /// Rebind paths only through the exact current alias/class captured by the original checked compilation.
    fn current(&self, project: &ProjectManifest, index: &LibraryManifestIndex) -> CliResult<DependencySpec> {
        let source = match &self.source {
            CheckedRustSource::Registry => DependencySource::Registry,
            CheckedRustSource::Git { url, reference } => DependencySource::Git {
                url: url.clone(),
                reference: match reference {
                    CheckedGitReference::Branch(value) => GitReference::Branch(value.clone()),
                    CheckedGitReference::Tag(value) => GitReference::Tag(value.clone()),
                    CheckedGitReference::Rev(value) => GitReference::Rev(value.clone()),
                },
            },
            CheckedRustSource::Provider { alias } => DependencySource::Path {
                path: index
                    .loaded_artifact(alias)
                    .ok_or_else(|| invalid("checked provider binding is no longer admitted"))?
                    .crate_root
                    .clone(),
            },
            CheckedRustSource::DeclaredRust { alias } => project
                .rust_dependencies()
                .get(alias)
                .ok_or_else(|| invalid("checked Rust source declaration is missing"))?
                .source
                .clone(),
            CheckedRustSource::StandardLibrary { crate_name } => {
                declared_stdlib_dependency(crate_name)?
                    .ok_or_else(|| invalid("checked standard dependency binding is missing"))?
                    .source
            }
        };
        if matches!(
            self.source,
            CheckedRustSource::Provider { .. }
                | CheckedRustSource::DeclaredRust { .. }
                | CheckedRustSource::StandardLibrary { .. }
        ) && !matches!(source, DependencySource::Path { .. })
        {
            return Err(invalid("checked physical source binding changed its source class"));
        }
        Ok(DependencySpec {
            crate_name: self.crate_name.clone(),
            version: self.version.clone(),
            features: self.features.clone(),
            default_features: self.default_features,
            source,
            optional: self.optional,
            package: self.package.clone(),
        })
    }
}

/// Exact current paths are compared only while capturing; no digest-only source-owner substitution is accepted.
fn same_path(left: &Path, right: &Path) -> CliResult<bool> {
    Ok(std::fs::canonicalize(left).map_err(|error| invalid(error.to_string()))?
        == std::fs::canonicalize(right).map_err(|error| invalid(error.to_string()))?)
}

/// Require package-owned source provenance; outside modules require a separate explicit current source binding.
fn source_relative(root: &Path, source: &Path) -> CliResult<String> {
    let relative = source
        .strip_prefix(root)
        .map_err(|_| invalid("checked source is outside its package"))?;
    let relative = relative
        .to_str()
        .ok_or_else(|| invalid("checked source path is not UTF-8"))?
        .replace('\\', "/");
    safe_relative(&relative)?;
    Ok(relative)
}

/// Refuse traversal, absolute paths and platform-dependent source replay coordinates.
fn safe_relative(value: &str) -> CliResult<PathBuf> {
    super::super::output_paths::validated_project_output_relative_path(value, "checked source provenance")
}

/// Keep replay failures within the normal checked preparation diagnostic family.
fn invalid(value: impl Into<String>) -> CliError {
    CliError::failure(value.into())
}

